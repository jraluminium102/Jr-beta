#!/usr/bin/env node
/**
 * กวาดหน้า "🔍 เทียบคิดราคา 4.0 ↔ ใบตัด" ทุกรุ่น ทุกรูปแบบ ทุกจำนวนบาน
 * ใช้ตอนไล่ให้เขียวล้วน — `node scripts/sweep-compare.mjs [prodId ...]`
 */
import fs from "node:fs";
import { compareCut, COMPARABLE } from "../src/lib/calculator40/compare-cut.ts";
import { PRODUCTS } from "../src/lib/calculator40/products.mjs";
import { allowedPanes } from "../src/lib/calculator40/form-rules.ts";

const PB = JSON.parse(fs.readFileSync("src/lib/calculator40/pricebook.json", "utf8"));

// ⚠⚠ ต้องจำลอง "มีราคาสโตร์" ก่อนกวาด ไม่งั้นเทสนี้วัดคนละเรื่องกับของจริง (เจ้าของเจอเอง 2 ก.ย.69)
//   ราคาสโตร์อยู่ในฐานข้อมูล เครื่องที่รันเทสไม่มี → PB.SKUPRICE ว่าง
//   → รุ่นที่ตั้งค่าให้ "ค่าของมาจากใบตัด" (HW_FROM_CUTLIST) จะโดน engine ถอยไปใช้สูตรเก่าทุกครั้ง
//     (engine.mjs "กันคิดต่ำกว่าจริงเงียบ ๆ" — ไม่มีราคาแม้ตัวเดียว = ไม่ใช้ทั้งชุด)
//   = เทสไปวัด "สูตรเก่า vs ใบตัด" ทั้งที่ของจริงบนเว็บใช้ "ใบตัด vs ใบตัด"
//   เดิมมันเขียวได้เพราะ compare-cut มีบั๊กเทียบตัวเองกับตัวเอง พอแก้บั๊กเลยแดง 43 ที่
//   ทางที่ถูกคือให้เทสอยู่ในสภาพเดียวกับของจริง: ใส่ราคาหลอกให้ทุกรหัส (ค่าไม่สำคัญ เทสนี้เทียบ "จำนวน" ไม่ใช่เงิน)
PB.SKUPRICE = new Proxy(PB.SKUPRICE ?? {}, { get: (t, k) => (typeof k === "string" && k ? (t[k] ?? 1) : t[k]) });

// จุดที่ "ตั้งใจต่าง" — ต้องมีเหตุผลกำกับเสมอ ห้ามใส่เพื่อปิดเทสเฉย ๆ
// 24 ส.ค.69: ว่างแล้ว — เจ้าของเคาะ PC Door (รหัส F#### ลงใบตัด + แถวที่ชีตตกหล่น) และอุปกรณ์เฟี้ยมยกลงใบตัดครบ
const KNOWN = {
  // บานโซลิด — เจ้าของเคาะ 4 ก.ย.69 "บานโซลิด เอาตามคิดราคา" (กลอนใบลองสลับเป็น CDQ JR00596 + ปลายกลอน JR00598 แล้ว)
  //   3 บรรทัดที่เหลือ = คนละหน่วยโดยธรรมชาติ ไม่ใช่ของขาด:
  //     ① ลูกฟูก2ทาง JR00249 · ② เส้นคาดตาราง JR00263 — คิดราคานับ "เส้น 6 ม. ที่ต้องซื้อ" · ใบตัดนับ "ชิ้นที่ตัด"
  //     ③ ซิลิโคน JR00504 — ใบตัดไม่มีบรรทัดของสิ้นเปลือง
  bansolid: ["ลูกฟูก2ทาง 2 ฝั่ง", "เส้นคาดตาราง 2 ฝั่ง", "ซิลิโคน"],
  // บานยก — ใบตัดไม่มีบรรทัดซิลิโคน (อุปกรณ์ที่เหลือขึ้น "ไม่สต็อก สั่งใหม่" ทั้งหมด ไม่นับว่าไม่ตรง)
  banyok: ["ซิลิโคน"],
};

// รุ่นที่ "ดึงขึ้นหน้าเทสดิบ ๆ" แต่ยังไม่ยกเครื่อง BOM ให้ตรงใบตัด → ยังไม่รวมใน gate เขียว
//   27 ส.ค.69: ว่างแล้ว — roof (กันสาด) ยกเครื่องเสร็จ โครงออกรหัสกล่องครบ เข้า gate ปกติ (ดู scripts/verify-roof.mjs)
//   31 ส.ค.69: +banyok — ดึงขึ้นหน้าเทียบตามที่เจ้าของขอ แต่ BOM ยังยึด "ไฟล์ถอดทุน v20" ซึ่งจำนวนไม่ตรงใบตัด FUJI HUNG
//     ต่าง 3 บรรทัด (ยาวรวม/รหัส): B28015 กล่องร่องมีสกรู · B28012 อแดปเตอร์รูสกรู · B28011 กรอบบาน
//     ✅ เจ้าของเคาะ 31 ส.ค.69: "ยึดไฟล์ v20" — ไม่แก้จำนวนตามใบตัด (ถ้ายึดใบตัด ทุนจะขยับ 5,282.64 → 5,546.06)
//     อุปกรณ์เทียบกันไม่ได้โดยธรรมชาติ: คิดราคาซื้อเป็น "กล่องอุปกรณ์" ทั้งชุด · ใบตัดแตกเป็นชิ้น 06-0xx
//   2 ก.ย.69: +pcdoor — ตั้งค่าให้ "ค่าของมาจากใบตัด" ไว้แล้ว แต่ใช้จริงไม่ได้สักครั้ง
//     ใบตัด PC Door มี 2 รายการที่ "ไม่มีรหัสสโตร์" คือ หัวต่อราง (1) · ฝาครอบราง (2)
//     engine เจอรายการไม่มีราคาแม้ตัวเดียว = ถอยไปใช้สูตรเก่าทั้งชุด → คิดเงินด้วยรายการเก่าเสมอ
//     ⇒ ต้องให้เจ้าของตั้งรหัส+ราคา 2 ตัวนี้ในสโตร์ก่อน แล้ว pcdoor จะเขียวเองทันที (เอาออกจากลิสต์นี้ได้)
//   4 ก.ย.69: banyok เข้า gate แล้ว — เจ้าของสั่ง "เอาตามใบตัด ไม่ต้องผูกรหัส" → เส้นอลูตรงครบ อุปกรณ์เป็นของสั่งตามงาน
const RAW_NOT_READY = new Set(["pcdoor"]);

const only = process.argv.slice(2);
const ids = (only.length ? only : [...COMPARABLE].filter((id) => !RAW_NOT_READY.has(id))).filter((id) => PRODUCTS[id]);

let ok = 0;
let bad = 0;
for (const id of ids) {
  const prod = PRODUCTS[id];
  const forms = prod.forms?.length ? prod.forms : [""];
  for (const form of forms) {
    for (const p of allowedPanes(prod, form)) {
      const r = compareCut(PB, {
        prodId: id,
        w: 200,
        h: 200,
        p,
        form,
        color: "white",
        glassType: "เขียว 6มม.",
        spec: {},
      });
      if (r.note) continue;
      // สีเดียวกับหน้าจอ (CompareClient): แดง=จำนวนต่าง/มีแต่ใบตัด · เหลือง=มีแต่คิดราคา · เทา=ไม่มีรหัส (แค่บอกว่ายังไม่ผูกสโตร์)
      const diff = [...(r.alu || []), ...(r.hardware || [])].filter(
        (x) =>
          (x.status === "จำนวนต่าง" || x.status === "มีแต่ใบตัด" || x.status === "มีแต่คิดราคา") &&
          !(x.name in KNOWN) &&
          !(Array.isArray(KNOWN[id]) && KNOWN[id].includes(x.name)),   // ยกเว้นรายชื่อ "ตั้งใจต่าง" เฉพาะรุ่นนั้น
      );
      if (!diff.length) {
        ok++;
        continue;
      }
      bad++;
      const detail = diff
        .map((x) => `${x.name}[${x.calcPieces ?? x.calcQty}/${x.cutPieces ?? x.cutQty}]`)
        .join(" · ");
      console.log(`❌ ${id.padEnd(11)} ${String(form).padEnd(26)} ${p}บาน  ${detail}`);
    }
  }
}
console.log(`\nรวม ✅ ${ok} · ❌ ${bad}`);
process.exit(bad ? 1 : 0);
