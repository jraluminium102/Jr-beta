#!/usr/bin/env node
/**
 * calc-alu-kg — คำนวณน้ำหนัก กก./เส้น ของกล่อง/ฉาก จากขนาด+ความหนา
 *   node scripts/calc-alu-kg.mjs
 *
 * เจ้าของสั่ง 9 ต.ค.69 "คุณกะน้ำหนักจากกล่องที่มีน้ำหนักได้ไหม ลองคำนวณเอา"
 *   กล่องกลวงสี่เหลี่ยม: พื้นที่หน้าตัด = 2 × หนา × (กว้าง + สูง − 2×หนา)
 *   ฉาก (ขาสองข้าง):    พื้นที่หน้าตัด = หนา × (ขา1 + ขา2 − หนา)
 *   น้ำหนัก กก./ม. = พื้นที่ (ตร.มม.) × 0.0027   (อลู 2.70 g/cm³)
 *
 * ① ตรวจสูตรกับเส้นที่รู้น้ำหนักจริงก่อน ② ค่อยกะตัวที่ไม่มีในแคตตาล็อก
 */
const IN = 25.4;
const RHO = 0.0027;                       // ตร.มม. → กก./ม.
export const kgmBox = (h, w, t) => 2 * t * (h + w - 2 * t) * RHO;
export const kgmAngle = (a, b, t) => t * (a + b - t) * RHO;
const bar = (kgm, len = 6) => Math.round(kgm * len * 1000) / 1000;

// ── ① ตรวจสูตร: เส้นที่รู้น้ำหนักจริง (ไฟล์/แคตตาล็อก/เจ้าของ) ──
const CHECK = [
  ["กล่อง 1\"×1\" หนา 1.2", kgmBox(1 * IN, 1 * IN, 1.2), 1.88],
  ["กล่อง 1\"×4\" หนา 1.5", kgmBox(1 * IN, 4 * IN, 1.5), 6.05],
  ["กล่อง 1.6\"×4\" หนา 1.5", kgmBox(1.75 * IN, 4 * IN, 1.5), 6.978],
  ["กล่อง 2\"×4\" หนา 1.5", kgmBox(2 * IN, 4 * IN, 1.5), 7.29],
  ["กล่อง 4\"×4\" หนา 2.0", kgmBox(4 * IN, 4 * IN, 2.0), 12.954],
  ["กล่อง 1.2\"×1.2\" หนา 1.5", kgmBox(1.2 * IN, 1.2 * IN, 1.5), 2.778],
  ["กล่อง 1×5 ซม. หนา 0.9", kgmBox(10, 50, 0.9), 1.704],
  ["ฉาก 2\" (½×2) หนา 1.6", kgmAngle(0.5 * IN, 2 * IN, 1.6), 1.63],
  ["ฉาก 6 หุน (¾×¾) หนา 1.6", kgmAngle(0.75 * IN, 0.75 * IN, 1.6), 1.0],
  ["ฉาก 4\" (½×4) หนา 1.2", kgmAngle(0.5 * IN, 4 * IN, 1.2), 2.208],
];
console.log("═══ ① ตรวจสูตรกับของจริง ═══");
console.log("  รายการ".padEnd(34) + "สูตรได้   ของจริง   ต่าง");
let worst = 0;
for (const [name, kgm, real] of CHECK) {
  const got = bar(kgm);
  const pct = (got - real) / real * 100;
  worst = Math.max(worst, Math.abs(pct));
  console.log("  " + name.padEnd(32) + String(got).padStart(7) + "   " + String(real).padStart(7) + "   " + (pct > 0 ? "+" : "") + pct.toFixed(1) + "%");
}
console.log("  → คลาดเคลื่อนสูงสุด " + worst.toFixed(1) + "%");

// ── ② กะน้ำหนักเส้นที่ไม่มีในแคตตาล็อก ──
//    กล่องใช้ความหนา 1.5 มม. ตามกฎเจ้าของ · เส้นใหญ่ 4"×6" โชว์ 2.0 ให้เทียบด้วย (4"×4" ของจริงหนา 2.0)
const GUESS = [
  ["กล่อง 1\"×1.2\"", kgmBox(1 * IN, 1.2 * IN, 1.5), "1.5 มม."],
  ["กล่อง 1.6\"×5\"", kgmBox(1.75 * IN, 5 * IN, 1.5), "1.5 มม."],
  ["กล่อง 2\"×6\"", kgmBox(2 * IN, 6 * IN, 1.5), "1.5 มม."],
  ["กล่อง 2\"×6\" (ถ้าหนา 2.0)", kgmBox(2 * IN, 6 * IN, 2.0), "2.0 มม."],
  ["กล่อง 4\"×6\"", kgmBox(4 * IN, 6 * IN, 1.5), "1.5 มม."],
  ["กล่อง 4\"×6\" (ถ้าหนา 2.0)", kgmBox(4 * IN, 6 * IN, 2.0), "2.0 มม. — 4\"×4\" ของจริงหนา 2.0"],
  ["กล่อง 1×5 ซม.", kgmBox(10, 50, 1.5), "1.5 มม."],
  ["ฉาก 3\" (½×3)", kgmAngle(0.5 * IN, 3 * IN, 1.6), "1.6 มม. (ฉากบ้านนี้ใช้ 1.6)"],
];
console.log("\n═══ ② กะน้ำหนักเส้นที่แคตตาล็อกไม่มี ═══");
for (const [name, kgm, note] of GUESS)
  console.log("  " + name.padEnd(30) + String(bar(kgm)).padStart(7) + " กก./เส้น 6 ม.   (" + Math.round(kgm * 1000) / 1000 + " กก./ม. · " + note + ")");
