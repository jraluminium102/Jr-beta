#!/usr/bin/env node
/**
 * verify-roof-slide — หลังคาเลื่อน (roof_slide) ต้องตรงชีต "คิดทุน หลังคาเลื่อน" ในไฟล์ถอดทุน v9
 * ─────────────────────────────────────────────────────────────────────────────
 * ⚠ รุ่นนี้ "ไม่มีไฟล์ตัดประกอบ" (เจ้าของยืนยัน 27 ส.ค.69 "เอาแค่คิดราคาพอ")
 *   → ชีตถอดทุนคือแหล่งความจริงเดียว ห้ามคิดตัวเลขขึ้นมาเอง
 *
 * ⚠ นิยามจากเจ้าของ 26 ก.ย.69: กว้าง×ยื่นที่กรอก = "ผืนรวม" แบ่งเป็นบานเลื่อนเท่า ๆ กัน P บาน · ใต้บานโล่ง
 *   ส่วนติดตายมีเฉพาะตอนกรอกช่อง fixw → ชุดอ้างอิงของชีต (ติดตาย 400×200 + เลื่อน 150 ×2 บาน)
 *   = ผืนรวมกว้าง 700 ยื่น 200 · fixw 400 · 2 บาน (บานละ 150×200) → ได้ค่าแรงตรงชีต 5,093 / 10,409 เป๊ะ
 *
 * ตัวเลขอ้างอิงเดิมจากชีต (ก่อนเปลี่ยนโมเดล — เก็บไว้ดูประวัติ):
 *   ติดตาย(วัสดุ) 24,390 · เลื่อน(วัสดุ) 24,340 · ราง 2,652 · ค่าแรงผลิต 10,050 · ติดตั้ง 19,125
 *   ⚠ ต่างชีต 660 บาท = กล่องเหล็ก 1"×1" ราคาสโตร์ 110 vs ชีต 170 (×11 เส้น) — รอเจ้าของเคาะว่าใช้ราคาไหน
 *
 *   node scripts/verify-roof-slide.mjs
 */
import fs from "node:fs";
import { computeCost } from "../src/lib/calculator40/engine.mjs";
import { PRODUCTS } from "../src/lib/calculator40/products.mjs";

const PB = JSON.parse(fs.readFileSync("src/lib/calculator40/pricebook.json", "utf8"));
let pass = 0, fail = 0;
const ok = (label, cond, got = "") => { cond ? pass++ : fail++; console.log(`  ${cond ? "✅" : "❌"} ${label}${cond || got === "" ? "" : `  (${got})`}`); };

const P = PRODUCTS.roof_slide;
// ชุดอ้างอิง = ชีต "คิดทุน หลังคาเลื่อน" v1 (ติดตาย 400×200 · บานเลื่อน 150 กว้าง 2 บาน)
//   เขียนในภาษาโมเดลใหม่: ผืนรวม 700×200 · ส่วนติดตาย 400 ซม. → ช่วงเลื่อน 300 แบ่ง 2 บาน = บานละ 150×200
const C = (o = {}) => computeCost(PB, P, {
  w: 700, h: 200, p: 2, form: "เลื่อนข้าง", material: "ไวนิล",
  color: "white", colorKey: "white", spec: { fixw: 400 }, addons: {}, ...o,
});
// ผืนเลื่อนล้วน (ไม่มีฟิก) = ที่เจ้าของบอกว่าเป็นความหมายตั้งต้นของ "หลังคาเลื่อน 400×200 2 บาน"
const PLAIN = (o = {}) => computeCost(PB, P, {
  w: 400, h: 200, p: 2, form: "เลื่อนข้าง", material: "ไวนิล",
  color: "white", colorKey: "white", spec: {}, addons: {}, ...o,
});
const C2 = PLAIN;   // ชื่อสั้นไว้ใช้ในชุดทดสอบส่วนติดตาย
const sum = (r, re) => Math.round(r.lines.filter((l) => re.test(l.name)).reduce((s, l) => s + (Number(l.amount) || 0), 0));
const line = (r, re) => r.lines.find((l) => re.test(l.name));

// ── ① ตรงชีตทีละก้อน ──
console.log("\n═══ ① ทุนแต่ละก้อน = ชีตถอดทุน (ไวนิล · 400×200 + เลื่อน 150×150 ×2) ═══");
{
  const r = C();
  // ต่างชีต 660 = กล่องเหล็ก 1"×1" คนละราคา (สโตร์ 110 · ชีต 170) — ยอมรับไว้ก่อน รอเจ้าของเคาะ
  // 3 ก.ย.69 v20.1: ติดตาย −602 = ฝาครอบไวนิล 16→6 เส้น (1 เส้น/แผ่น) −2,450 + แผ่น 6 ×1.2 buf_roof +1,848
  //                 เลื่อน −728 = ฝาครอบ 12→4 เส้น −1,960 + แผ่น 4 ×1.2 +1,232
  // 21 ก.ย.69 พอร์ตไฟล์ v1: ตัวเลขชุดนี้ของเดิมมาจากชีต v20 — ตอนนี้ยึดชีต "คิดทุน หลังคาเลื่อน" ของ v1
  //   ตรวจแล้วด้วยอินพุตของชีตเอง (ติดตาย 400×200): ทุนติดตาย = 21,841.8 ตรงเป๊ะ · ล้อ+ลากจูง 8,800 ตรงเป๊ะ
  //   ⚠ "ส่วนเลื่อน" ชีตกรอกกว้างรวมทุกบาน แต่เว็บถามต่อบาน → ก้อนเลื่อน/รางของด่านนี้เป็นของอินพุตเว็บ (2 บาน)
  ok("ติดตาย (วัสดุ) 21,842 ตรงชีต v1 เป๊ะ", sum(r, /ติดตาย/) === 21842, String(sum(r, /ติดตาย/)));
  // 26 ก.ย.69 บานเลื่อนลึกเท่าผืนเสมอ (150×200) ของเดิมชีตกรอกบานตื้นกว่าผืน (150×150) → ก้อนเลื่อนสูงขึ้น
  ok("เลื่อน (วัสดุ) 16,316 (2 บาน · บานละ 150×200)", sum(r, /เลื่อน\)/) === 16316, String(sum(r, /เลื่อน\)/)));
  ok("ราง (2 ฝั่ง) 16,320 = 8,160 ของชีต × 2 บาน", sum(r, /^ราง/) === 16320, String(sum(r, /^ราง/)));
  // 3 ก.ย.69 ตารางค่าแรงซิงก์ตามไฟล์ v20.1 (หลังคาเลื่อน ผลิต 3,500 + 113.75/ตร.ม. · ติดตั้ง 8,400 + 143.5/ตร.ม.)
  //   พื้นที่ 12.5 ตร.ม. → ผลิต 4,922 · ติดตั้ง 10,194 (เดิมเป็นเรตล้วนจากไฟล์ตัวแรก 804/1,530 ต่อ ตร.ม.)
  // พื้นที่ค่าแรง = ผืนรวม 7.0×2.0 = 14 ตร.ม. = H3 + J3×บาน ของชีตเป๊ะ (8 + 3×2)
  ok("พื้นที่คิดค่าแรง 14 ตร.ม. = ชีต (H3 8 + J3 3 × 2 บาน)", r.laborCalc.area === 14, String(r.laborCalc.area));
  ok("ค่าแรงผลิต 5,093 ตรงชีต ⑤ เป๊ะ", Math.round(r.labor.prod) === 5093, String(Math.round(r.labor.prod)));
  ok("ค่าแรงติดตั้ง 10,409 ตรงชีต ⑥ เป๊ะ", Math.round(r.labor.install) === 10409, String(Math.round(r.labor.install)));
}

// ── ② จุดที่เคยตรึงตายตัว ต้องขยับตามที่กรอกแล้ว ──
console.log("\n═══ ② ช่องที่เคยตรึงตายตัว (ของเดิมกรอกไม่ได้) ═══");
{
  ok("มีช่องกรอกส่วนติดตาย (0 = ผืนเลื่อนล้วน)", (P.specOpts ?? []).some((o) => o.key === "fixw" && o.type === "number" && o.def === "0"));
  ok("ไม่ถามขนาดบานเลื่อนแล้ว (ได้จากผืนรวม ÷ บาน)", !(P.specOpts ?? []).some((o) => o.key === "slidew" || o.key === "slideh"));
  ok("มีช่องเลือกแป (ชีตมี B4)", (P.specOpts ?? []).some((o) => o.key === "batten"));
  const base = C().cost.total;
  // ผืนรวมเท่าเดิม ฟิกมากขึ้น = ช่วงเลื่อนน้อยลง = ถูกลง (ส่วนเลื่อนมีราง+ล้อ+ลากจูง)
  ok("ฟิกมากขึ้น = ถูกลง (ช่วงเลื่อนน้อยลง)", C({ spec: { fixw: 500 } }).cost.total < base, String(Math.round(C({ spec: { fixw: 500 } }).cost.total)));
  // ⚠ ไม่ได้ลดแบบเส้นตรง: ฟิกแคบ ๆ (เช่น 25 ซม.) ยังต้องมีจันทัน 2 แนว + แผ่นมุงของตัวเอง 1 แผ่น + เพลท
  //   → ทุนขึ้นก่อนแล้วค่อยลงเมื่อฟิกกว้างพอ (ตรงตามสูตรฝั่ง "ติดตาย" ของชีต ไม่ใช่บั๊กปัดเศษ)
  //   QA 26 ก.ย.69 จับไว้แล้ว — ล็อกพฤติกรรมนี้ไว้กันมีคน "แก้" เงียบ ๆ
  ok("ฟิกแคบ 25 ซม. แพงกว่าไม่มีฟิก (มีโครง+แผ่นของตัวเอง)", C2({ spec: { fixw: 25 } }).cost.total > C2().cost.total,
    Math.round(C2({ spec: { fixw: 25 } }).cost.total) + " vs " + Math.round(C2().cost.total));
  ok("ฟิกกว้าง 200 ซม. ถูกกว่าไม่มีฟิกชัดเจน", C2({ spec: { fixw: 200 } }).cost.total < C2().cost.total,
    Math.round(C2({ spec: { fixw: 200 } }).cost.total) + " vs " + Math.round(C2().cost.total));
  ok("ผืนเลื่อนล้วน = ไม่มีบรรทัดส่วนติดตายเลย", PLAIN().lines.filter((l) => /\(ติดตาย\)/.test(l.name) && Number(l.amount) > 0).length === 0);
  ok("ผืนเลื่อนล้วน: พื้นที่ค่าแรง = กว้าง×ยื่น (8 ตร.ม.)", PLAIN().laborCalc.area === 8, String(PLAIN().laborCalc.area));
  ok("ผืนกว้างขึ้น = แพงขึ้น", PLAIN({ w: 600 }).cost.total > PLAIN().cost.total);
  // แป: เดิมกล่องแปคู่ถูกกว่า — ราคากล่องในไฟล์ v1 เปลี่ยน ทิศทางเลยไม่คงที่ · ตรวจแค่ว่า "เลือกแล้วมีผลจริง"
  ok("เลือกแปคู่แล้วทุนเปลี่ยนจริง", C({ spec: { batten: "แปคู่" } }).cost.total !== base,
    Math.round(C({ spec: { batten: "แปคู่" } }).cost.total) + " vs " + Math.round(base));
  ok("บานเลื่อนมากขึ้น = แพงขึ้น", C({ p: 4 }).cost.total > base);
  // ราง: เลื่อนยื่น = ยาวตามยื่น · รูปแบบอื่น = ยาวตามกว้าง (ชีต D12) — ต้องต่างกันเมื่อ กว้าง ≠ ยื่น
  const s = { fixw: 100 };
  ok("รูปแบบเลื่อนเปลี่ยน → ความยาวรางเปลี่ยน (ชีต D12)",
    sum(C({ form: "เลื่อนยื่น", spec: s }), /^ราง/) !== sum(C({ form: "เลื่อนข้าง", spec: s }), /^ราง/),
    `${sum(C({ form: "เลื่อนยื่น", spec: s }), /^ราง/)} vs ${sum(C({ form: "เลื่อนข้าง", spec: s }), /^ราง/)}`);
}

// ── ③ แผ่นไวนิลตัดจากแผ่นยาว 7 ม. (ชีต H7/J7) ──
console.log("\n═══ ③ แผ่นไวนิล — 1 แผ่น (ยาว 7 ม.) ตัดได้หลายแถบ ═══");
{
  // ติดตาย 400 กว้าง → 16 แถบ · ยื่น 200 → แผ่นละ 3 แถบ → ซื้อ 6 แผ่น (ไม่ใช่ 16)
  ok("ติดตาย ยื่น 200 → 6 แผ่น (ไม่ใช่ 16)", line(C(), /^แผ่นไวนิล \(ติดตาย\)/)?.qty === 6, String(line(C(), /^แผ่นไวนิล \(ติดตาย\)/)?.qty));
  // ยื่น 350 → แผ่นละ 2 แถบ → 8 แผ่น
  ok("ยื่นลึกขึ้น (350) → ตัดได้/แผ่นน้อยลง → 8 แผ่น", line(C({ h: 350 }), /^แผ่นไวนิล \(ติดตาย\)/)?.qty === 8, String(line(C({ h: 350 }), /^แผ่นไวนิล \(ติดตาย\)/)?.qty));
  ok("ผืนเลื่อนล้วน: แผ่นไวนิลไปอยู่ก้อนเลื่อนทั้งหมด", (line(PLAIN(), /^แผ่นไวนิล \(เลื่อน\)/)?.qty ?? 0) > 0 && !line(PLAIN(), /^แผ่นไวนิล \(ติดตาย\)/));
  // ฝาครอบยังนับต่อแถบเหมือนเดิม (ชีต H8 ไม่มีการหารแผ่น)
  ok("ฝาครอบไวนิล = 1 เส้น/แผ่น → 6 (v20.1 H8 หารแผ่นแล้ว · เดิม 16 ต่อแถบ)", line(C(), /^ฝาครอบไวนิล \(ติดตาย\)/)?.qty === 6, String(line(C(), /^ฝาครอบไวนิล \(ติดตาย\)/)?.qty));
}

// ── ④ ค่าแรงคิดจากพื้นที่ ติดตาย + เลื่อน×บาน ──
console.log("\n═══ ④ ค่าแรงคิดจากพื้นที่รวม (ชีต D14/D15 = เรต × (H3 + J3×บาน)) ═══");
{
  ok("ไม่ฝังค่าแรงเป็นบรรทัดวัสดุแล้ว", !P.consum.some((c) => /ค่าแรง/.test(String(c.name))));
  ok("ผูกตารางค่าแรงกลาง 'หลังคาเลื่อน'", P.laborKey === "หลังคาเลื่อน");
  ok("พื้นที่ = ติดตาย + เลื่อน×บาน", P.areaExpr === "fArea + sArea*P");
  const r = C(), rate = PB.LABOR["หลังคาเลื่อน"];
  ok("ค่าแรงผลิต = ฐาน + เรต × 14 ตร.ม. (ตามตารางกลาง)", Math.round(r.labor.prod) === Math.round(rate.pBase + rate.pRate * 14));
  // ผืนรวมเท่าเดิม เพิ่มจำนวนบาน = ซอยบานให้เล็กลง ค่าแรงเท่าเดิม (แต่ราง/ล้อเพิ่ม → ทุนขึ้น)
  ok("ผืนเท่าเดิม บานเยอะขึ้น → ค่าแรงเท่าเดิม", Math.round(PLAIN({ p: 4 }).labor.prod) === Math.round(PLAIN().labor.prod));
  ok("ผืนเท่าเดิม บานเยอะขึ้น → ทุนแพงขึ้น (ราง+ล้อ+ลากจูง)", PLAIN({ p: 4 }).cost.total > PLAIN().cost.total);
  ok("ผืนโตขึ้น → ค่าแรงเยอะขึ้น", PLAIN({ w: 600 }).labor.prod > PLAIN().labor.prod);
}

// ── ⑤ วัสดุมุงทุกชนิดต้องมีราคา ──
console.log("\n═══ ⑤ วัสดุมุงครบ 8 ชนิด ต้องออกราคา ไม่มี 0 ═══");
{
  const bad = [];
  for (const m of P.materials) {
    const r = C({ material: m });
    const sheets = r.lines.filter((l) => l.cat === "consum" && /แผ่น|ชินโคร์|กระจก|เมทัล/.test(l.name) && l.qty > 0);
    if (!sheets.length || sheets.some((l) => !(l.unitPrice > 0))) bad.push(m);
  }
  ok(`${P.materials.length} ชนิด ออกราคาครบ`, bad.length === 0, bad.join(","));
}

console.log(`\n═══ สรุป: ✅ ${pass} ผ่าน · ❌ ${fail} ไม่ผ่าน ═══`);
process.exit(fail ? 1 : 0);
