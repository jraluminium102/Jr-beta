  const sizes = [[140, 150, 2], [200, 200, 2], [240, 200, 2], [270, 300, 3], [390, 300, 3], [600, 300, 3]]
    .filter((s) => s[2] <= (prod.maxP ?? 9) && s[2] >= (prod.minP ?? 1));
