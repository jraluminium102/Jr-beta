import { buildSideColumns, installerScopeFromNote, customerPrepFromNote, noteBulletsFromDetail } from "../src/lib/cover-sheet/generate.mjs";

let pass = 0, fail = 0;
const eq = (name, got, want) => {
  const g = JSON.stringify(got), w = JSON.stringify(want);
  if (g === w) { pass++; }
  else { fail++; console.log(`✗ ${name}\n   got : ${g}\n   want: ${w}`); }
};

// ── เคสจริง คุณยุทธ QT2569070080 (ประตูบานเลื่อน · หมายเหตุ 3 บรรทัด) ──
const detail = `- ประตูอลูมิเนียมลูกฟูกเรียบบานเลื่อนเปิดคู่กลางรางล่าง (รุ่นกันน้ำ) พร้อมกระจกติดตายด้านข้าง (ใช้มือจับ Digital Door Lock เดิม)

หมายเหตุ
- ราคาที่เสนอรวมงานติดตั้งเฉพาะมือจับ Digital Door Lock เดิม แต่ไม่รวมงานเซ็ทระบบมือจับ หากพบปัญหาที่เกิดจากการใช้งาน ลูกค้าต้องประสานงานกับทางร้านผู้จำหน่ายมือจับโดยตรงเท่านั้น
- ราคาที่เสนอรวมงานรื้อประตูเดิม  ในกรณีที่เกิดความเสียหายจากการทำงาน เช่น วัสดุเดิมเป็นรอย กระจกแตก งานเก็บสี จะมีบริการเปลี่ยนใหม่และเก็บงานให้โดยไม่มีค่าใช้จ่าย แต่ไม่รวมวัสดุและสี (ลูกค้าดำเนินการเตรียมวัสดุและสีให้)
- ราคาที่เสนอรวมงานดรอปพื้น ในกรณีที่เกิดความเสียหายจากการทำงาน เช่น กระเบื้องพื้นแตกร้าว งานเก็บสี  จะมีบริการเปลี่ยนใหม่และเก็บงานให้โดยไม่มีค่าใช้จ่าย แต่ไม่รวมวัสดุและสี (ลูกค้าดำเนินการเตรียมวัสดุและสีให้)

รายละเอียดงาน
- อลูมิเนียมลายไม้ สี Golden Teak SMS
- กระจกเทมเปอร์ หนา 6 มม.`;

eq("noteBullets count", noteBulletsFromDetail(detail).length, 3);

const { mid, right } = buildSideColumns([{ name: "ประตูบานเลื่อน", detail }]);
eq("col2 (แจ้งช่าง) = ขอบเขตงาน ตัดสั้น", mid.map((l) => l.text), [
  "ติดตั้งเฉพาะมือจับ Digital Door Lock เดิม แต่ไม่รวมงานเซ็ทระบบมือจับ",
  "รื้อประตูเดิม",
  "ดรอปพื้น",
]);
eq("col3 (แจ้งลูกค้า) = ลูกค้าเตรียม… (dedup)", right.map((l) => l.text), [
  "ลูกค้าดำเนินการเตรียมวัสดุและสีให้",
]);

// ── หน่วยย่อย ──
eq("scope: ตัด 'หากพบ'", installerScopeFromNote("ราคาที่เสนอรวมงานรื้อประตูเดิม  ในกรณีที่..."), "รื้อประตูเดิม");
eq("scope: ไม่ใช่บรรทัดขอบเขต → ''", installerScopeFromNote("ราคานี้ยืน 30 วัน"), "");
eq("prep: ไม่มี 'ลูกค้า…เตรียม' → ''", customerPrepFromNote("ราคาที่เสนอรวมงานรื้อประตูเดิม"), "");
