#!/usr/bin/env node
/**
 * calc-channel-kg — คิดน้ำหนัก "กล่องเรียบ" (หน้าตัดเปิด 3 ด้าน) จากขนาด + ความหนา
 *   node scripts/calc-channel-kg.mjs
 *
 * เจ้าของอธิบาย 10 ต.ค.69: "กล่องเรียบจะมี 3 ด้าน น้ำหนักน้อยกว่ากล่อง 4x4 ที่มี 4 ด้าน"
 *
 * สูตรหน้าตัด (อลู 2.70 g/cm³ · เส้น 6 ม. แบบเมืองทอง)
 *   กล่องปิด 4 ด้าน : A = 2·t·(H + W − 2t)
 *   กล่องเรียบ 3 ด้าน: A = t·(2H + W − 2t)      ← ขาไป-กลับ 2 ขา + ท้อง 1 ด้าน
 *   กก./ม. = A(มม.²) × 0.0027
 *
 * ตัวตรวจว่าโมเดลถูก: กล่องเรียบ 1.6"×4" ที่เจ้าของให้มา 5.30 กก./เส้น
 *   ท้อง 101.6 · ขา 44.45 · หนา 1.75 มม. → 5.30 เป๊ะ (คลาด 0.0%)
 * และกล่องปิด 4"×4" = 12.954 กก./เส้น ย้อนได้ความหนา 2.0 มม. (ตรงกับที่เคยบันทึกไว้)
 */
const IN = 25.4;
const D = 0.0027;                    // มม.² → กก./ม.
const box = (h, w, t) => 2 * t * (h + w - 2 * t) * D;
const chan = (leg, web, t) => t * (2 * leg + web - 2 * t) * D;
const bar = (kgm, len = 6) => Math.round(kgm * len * 1000) / 1000;

const rows = [];
const add = (label, kg, note) => rows.push([label, kg, note]);

// ── ① ย้อนความหนาของกล่องปิด 4"×4" จากน้ำหนักจริง 12.954 กก./เส้น 6 ม. ──
{
  const target = 12.954 / 6;         // กก./ม.
  const s = IN * 4;
  // 2t(2s − 2t)·D = target → 4t² − 4st + target/D = 0
  const t = (4 * s - Math.sqrt(16 * s * s - 16 * (target / D))) / 8;
  add('กล่อง 4"×4" (ปิด 4 ด้าน · ของจริง 12.954)', bar(box(s, s, t)), "ย้อนได้ความหนา " + (Math.round(t * 100) / 100) + " มม.");
}

// ── ② ตรวจโมเดล 3 ด้าน กับค่าที่เจ้าของให้มา: กล่องเรียบ 1.6"×4" = 5.30 ──
for (const t of [1.5, 1.75, 2.0]) {
  const kg = bar(chan(1.75 * IN, 4 * IN, t));   // 1.6 นิ้ว = 1.75" = 44.45 มม. (กฎเจ้าของ)
  add('กล่องเรียบ 1.6"×4" หนา ' + t, kg, Math.abs(kg - 5.30) < 0.02 ? "✅ ตรงกับที่เจ้าของให้ (5.30)" : "ต่างจาก 5.30 " + (Math.round((kg - 5.3) * 100) / 100));
}

// ── ③ ที่ต้องการ: กล่องเรียบ 4"×4" ──
for (const t of [1.5, 1.75, 2.0]) {
  const s = 4 * IN;
  add('กล่องเรียบ 4"×4" หนา ' + t, bar(chan(s, s, t)), "เทียบกล่องปิด 12.954 = " + Math.round((bar(chan(s, s, t)) / 12.954) * 100) + "%");
}

const w = Math.max(...rows.map((r) => r[0].length));
for (const [a, b, c] of rows) console.log("  " + a.padEnd(w) + "  " + String(b).padStart(7) + " กก./เส้น 6 ม.   " + c);
