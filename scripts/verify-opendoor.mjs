// verify-opendoor.mjs — ด่านกัน "บานเปิด FUJI คิดของไม่ตรงไฟล์ตัดประกอบ"
// รัน:  node scripts/verify-opendoor.mjs
// หมายเหตุ: engine เก็บความยาวรวมเป็นเมตรปัด 2 ตำแหน่ง (1 ซม.) → เทียบเป็น มม. เผื่อ ±6
// ─────────────────────────────────────────────────────────────────────────────
// ต้นทาง: รวมใบตัด_JR_2 เพิ่มอุปกรณ์/JR_FUJI_บานเปิด-บานกระทุ้ง.xlsx
//   ชีต ประตูเดี่ยว/คู่ (มี-ไม่มีธรณี) · บานเปิด · บานเปิดคู่
// เจ้าของเคาะ 21 ส.ค.69:
//   · โปรไฟล์ชุดเดียวกันทั้งประตูและหน้าต่าง แต่ "อุปกรณ์คนละชุดเลย"
//   · กรอบบานเลือก 8 ซม. (F7943) / 10 ซม. (F7864) ได้อิสระ — หักคิ้วต่างกัน 80/60 vs 100/80
//   · รหัสยึด "ช่อง sku ในสโตร์" (F7938 · F7945) ไม่ใช่ชื่อที่มี B/C ต่อท้าย
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';
import { computeCost } from '../src/lib/calculator40/engine.mjs';
import { PRODUCTS } from '../src/lib/calculator40/products.mjs';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const PB = JSON.parse(fs.readFileSync(path.join(__dirname, '../src/lib/calculator40/pricebook.json'), 'utf8'));

let pass = 0, fail = 0;
const ok = (label, cond, got = '') => {
  cond ? pass++ : fail++;
  console.log(`  ${cond ? '✅' : '❌'} ${label}${cond || got === '' ? '' : `  (${got})`}`);
};
const near = (label, a, b, tol = 0.6) => ok(label, Math.abs(a - b) <= tol, `${a} ≠ ${b}`);

const P = PRODUCTS.open_door;
const run = (w, h, p, form, kind, frame) => computeCost(PB, P, {
  w, h, p, form, color: 'white', colorKey: 'white', glassType: 'เขียว 6มม.',
  spec: { odkind: kind, odframe: frame }, profitPct: 100, installProfitPct: 100,
});
/** ยาวตัด (มม.) + จำนวนท่อน ของบรรทัดที่ชื่อขึ้นต้นด้วย name */
const line = (r, name) => {
  const l = r.lines.find((x) => x.cat === 'alu' && x.name.startsWith(name));
  return l ? { mm: Math.round((l.lenM / l.pieces) * 1000), pcs: l.pieces, code: l.code } : null;
};
const hw = (r, sku) => r.lines.filter((x) => x.cat === 'hardware' && x.sku === sku).reduce((s, x) => s + x.qty, 0);

// ── ① ประตูเดี่ยว มีธรณี 900×2000 — ทุกท่อนตรงไฟล์ (ชีต "ประตูเดี่ยว มีธรณี") ────
console.log('\n═══ ① ประตูเดี่ยว มีธรณี 900×2000 · กรอบ 10 ซม. ═══');
{
  const r = run(90, 200, 1, 'มีธรณี', 'ประตู', '10 ซม. (F7864)');
  for (const [nm, mm, pcs, code] of [
    ['เฟรมข้าง', 2000, 2, 'F7859'],
    ['เฟรมบน', 850, 1, 'F7859'],
    ['เฟรมล่าง (ธรณี)', 850, 1, 'F7938'],
    ['ตบธรณี', 850, 1, 'F7960'],
    ['เสา (กรอบบาน)', 1963, 2, 'F7864'],
    ['ขวาง (กรอบบาน)', 863, 2, 'F7864'],
    ['คิ้วตั้ง', 1763, 2, 'F7935'],
    ['คิ้วขวาง', 703, 2, 'F7935'],
  ]) {
    const l = line(r, nm);
    ok(`${nm}: ${mm} มม. × ${pcs} ท่อน · ${code}`, !!l && Math.abs(l.mm - mm) <= 6 && l.pcs === pcs && l.code === code,
      l ? `${l.mm} × ${l.pcs} · ${l.code}` : 'ไม่มีบรรทัดนี้');
  }
  ok('ไม่มีชายล่าง (มีธรณีแล้ว)', !line(r, 'ชายล่าง'));
  ok('ไม่มีชนกลาง (บานเดี่ยว)', !line(r, 'ชนกลาง'));
}

// ── ② ประตูเดี่ยว ไม่มีธรณี — เสาหัก 18.5+7 · มีชายล่าง F7863 แทนธรณี ────────────
console.log('\n═══ ② ประตูเดี่ยว ไม่มีธรณี 900×2000 ═══');
{
  const r = run(90, 200, 1, 'ไม่มีธรณี', 'ประตู', '10 ซม. (F7864)');
  near('เสา = สูง−18.5−7 = 1975 มม.', line(r, 'เสา (กรอบบาน)')?.mm ?? 0, 1975, 6);
  near('ชายล่าง F7863 ยาวเท่าขวาง', line(r, 'ชายล่าง')?.mm ?? 0, line(r, 'ขวาง (กรอบบาน)')?.mm ?? -1, 6);
  ok('ไม่มีธรณี/ตบธรณี', !line(r, 'เฟรมล่าง (ธรณี)') && !line(r, 'ตบธรณี'));
  ok('น็อตเฟรม 6 ตัว (ไม่มีธรณี)', hw(r, 'JR00864') === 6, String(hw(r, 'JR00864')));
}

// ── ③ ประตูคู่ — ขวางหัก 18.5+1 · เสา/ขวาง/คิ้ว ×2 บาน · ชนกลาง 1 ต้น ──────────
console.log('\n═══ ③ ประตูคู่ มีธรณี 1800×2200 ═══');
{
  const r = run(180, 220, 2, 'มีธรณี', 'ประตู', '10 ซม. (F7864)');
  near('ขวาง = (กว้าง/2)−18.5−1 = 881 มม.', line(r, 'ขวาง (กรอบบาน)')?.mm ?? 0, 881, 6);
  ok('เสา 4 ท่อน · ขวาง 4 ท่อน (บานละ 2)', line(r, 'เสา (กรอบบาน)')?.pcs === 4 && line(r, 'ขวาง (กรอบบาน)')?.pcs === 4);
  ok('คิ้วตั้ง/ขวาง อย่างละ 4 ท่อน', line(r, 'คิ้วตั้ง')?.pcs === 4 && line(r, 'คิ้วขวาง')?.pcs === 4);
  near('ชนกลาง F7945 = สูง−27−27 = 2146 มม.', line(r, 'ชนกลาง')?.mm ?? 0, 2146, 6);
  ok('ชนกลาง 1 ต้น', line(r, 'ชนกลาง')?.pcs === 1);
  ok('CDQ + ปลายกลอน บานลอง อย่างละ 1', hw(r, 'JR00596') === 1 && hw(r, 'JR00598') === 1);
  ok('มือจับ KINGBO 2 ชุด (ทั้ง 2 บาน)', hw(r, 'JR00315') === 2, String(hw(r, 'JR00315')));
  ok('ตลับกุญแจ/ไส้กุญแจ อย่างละ 1 (เฉพาะบานหลัก)', hw(r, 'JR00551') === 1 && hw(r, 'JR00499') === 1);
}

// ── ④ 3-4 บาน: ชนกลาง = บาน−1 (เจ้าของสั่ง 21 ส.ค.69 "เพิ่มได้ แต่คิดราคาให้ถูก") ──
console.log('\n═══ ④ ประตู 3-4 บาน ═══');
for (const n of [3, 4]) {
  const r = run(240, 220, n, 'มีธรณี', 'ประตู', '10 ซม. (F7864)');
  ok(`${n} บาน: ชนกลาง ${n - 1} ต้น`, line(r, 'ชนกลาง')?.pcs === n - 1, String(line(r, 'ชนกลาง')?.pcs));
  ok(`${n} บาน: เสา ${2 * n} ท่อน`, line(r, 'เสา (กรอบบาน)')?.pcs === 2 * n, String(line(r, 'เสา (กรอบบาน)')?.pcs));
  ok(`${n} บาน: มือจับ ${n} ชุด · บานลอง ${n - 1} ชุด`, hw(r, 'JR00315') === n && hw(r, 'JR00596') === n - 1);
}

// ── ⑤ กรอบบาน 8 ซม. — สลับรหัสเสา/ขวาง + หักคิ้ว 80/60 ────────────────────────
console.log('\n═══ ⑤ กรอบบาน 8 ซม. (F7943) เทียบ 10 ซม. (F7864) ═══');
{
  const a = run(90, 200, 1, 'มีธรณี', 'ประตู', '10 ซม. (F7864)');
  const b = run(90, 200, 1, 'มีธรณี', 'ประตู', '8 ซม. (F7943)');
  ok('10 ซม. ใช้ F7864 · 8 ซม. ใช้ F7943', line(a, 'เสา (กรอบบาน)')?.code === 'F7864' && line(b, 'เสา (กรอบบาน)')?.code === 'F7943');
  near('คิ้วตั้ง 10 ซม. = เสา−200', line(a, 'คิ้วตั้ง')?.mm ?? 0, (line(a, 'เสา (กรอบบาน)')?.mm ?? 0) - 200, 6);
  near('คิ้วตั้ง 8 ซม. = เสา−160', line(b, 'คิ้วตั้ง')?.mm ?? 0, (line(b, 'เสา (กรอบบาน)')?.mm ?? 0) - 160, 6);
  near('คิ้วขวาง 10 ซม. = ขวาง−160', line(a, 'คิ้วขวาง')?.mm ?? 0, (line(a, 'ขวาง (กรอบบาน)')?.mm ?? 0) - 160, 6);
  near('คิ้วขวาง 8 ซม. = ขวาง−120', line(b, 'คิ้วขวาง')?.mm ?? 0, (line(b, 'ขวาง (กรอบบาน)')?.mm ?? 0) - 120, 6);
  ok('เลือกกรอบแล้วราคาเปลี่ยนจริง', Math.abs(a.cost.total - b.cost.total) > 1, `${a.cost.total} = ${b.cost.total}`);
}

// ── ⑥ หน้าต่าง — โปรไฟล์ชุดเดียวกัน แต่อุปกรณ์คนละชุด (เจ้าของย้ำ) ─────────────
console.log('\n═══ ⑥ หน้าต่างบานเปิด — อุปกรณ์คนละชุดกับประตู ═══');
{
  const w1 = run(60, 160, 1, 'มีธรณี', 'หน้าต่าง', '8 ซม. (F7943)');
  const w2 = run(120, 160, 2, 'มีธรณี', 'หน้าต่าง', '8 ซม. (F7943)');
  ok('เฟรมล่างหน้าต่างใช้ F7939', line(w1, 'เฟรมล่าง หน้าต่าง')?.code === 'F7939');
  ok('หน้าต่างไม่มีธรณี/ตบธรณี/ชายล่าง', !line(w1, 'เฟรมล่าง (ธรณี)') && !line(w1, 'ตบธรณี') && !line(w1, 'ชายล่าง'));
  ok('หน้าต่างไม่มีบานพับ (ใช้วิทโก้)', hw(w1, 'JR00489') === 0 && hw(w1, 'JR00559') === 2, `วิทโก้ ${hw(w1, 'JR00559')}`);
  ok('หน้าต่างไม่มีมือจับ/ไส้กุญแจของประตู', hw(w1, 'JR00315') === 0 && hw(w1, 'JR00499') === 0);
  ok('มือจับหน้าต่าง ใบ1 = 1 · ใบ2 = 0 (บานเดี่ยว)', hw(w1, 'JR00304') === 1 && hw(w1, 'JR00305') === 0);
  ok('บานคู่: มือจับ ใบ1 1 + ใบ2 1', hw(w2, 'JR00304') === 1 && hw(w2, 'JR00305') === 1);
  ok('CDQ กระทุ้ง = จำนวนบาน', hw(w2, 'JR00566') === 2, String(hw(w2, 'JR00566')));
  ok('ลูกเบี้ยว/รับล็อค = 2 ต่อบาน', hw(w2, 'JR00486') === 4 && hw(w2, 'JR00483') === 4);
  ok('น็อตเฟรมหน้าต่าง 8 ตัว', hw(w2, 'JR00864') === 8, String(hw(w2, 'JR00864')));
  ok('ยางหน้าต่างใช้ JR00770 (ประตูใช้ JR00771)',
    w1.lines.some((l) => l.cat === 'consum' && l.sku === 'JR00770')
    && run(90, 200, 1, 'มีธรณี', 'ประตู', '10 ซม. (F7864)').lines.some((l) => l.cat === 'consum' && l.sku === 'JR00771'));
}

// ── ⑦ รหัสต้องตรง "ช่อง sku ในสโตร์" — ห้ามมี B/C ต่อท้าย (เจ้าของยืนยัน 21 ส.ค.69) ──
console.log('\n═══ ⑦ รหัสอลูตรงกับ sku ในสโตร์ ═══');
{
  const codes = P.alu.map((a) => String(a.code));
  ok('ไม่มี F7938B หลงเหลือ', !codes.some((c) => c.includes('F7938B')));
  ok('ไม่มี F7945C หลงเหลือ', !codes.some((c) => c.includes('F7945C')));
  for (const c of ['F7859', 'F7938', 'F7939', 'F7960', 'F7863', 'F7935', 'F7945'])
    ok(`ใช้รหัส ${c}`, codes.some((x) => x === c));
  ok('เสา/ขวาง สลับ F7943 ↔ F7864 ตามกรอบบาน', codes.filter((c) => c.includes('F7943') && c.includes('F7864')).length === 2);
  ok('อุปกรณ์ทุกบรรทัดมีรหัสสโตร์', (P.hardware || []).every((h) => !!h.sku), (P.hardware || []).filter((h) => !h.sku).map((h) => h.name).join(','));
}

console.log(`\n═══ สรุป: ✅ ${pass} ผ่าน · ❌ ${fail} ไม่ผ่าน ═══`);
process.exit(fail ? 1 : 0);
