  ok('หน้าต่างไม่มีบานพับ (ใช้วิทโก้)', hw(w1, 'JR00489') === 0 && hw(w1, 'JR00559') === 2, `วิทโก้ ${hw(w1, 'JR00559')}`);
  ok('หน้าต่างไม่มีมือจับ/ไส้กุญแจของประตู', hw(w1, 'JR00315') === 0 && hw(w1, 'JR00499') === 0);
  // มือจับหน้าต่าง: เจ้าของสั่งเปลี่ยนเป็น KINGBO-FH3016 (27 ส.ค.69) — 4 รหัส (2 สี × ซ้าย/ขวา) ราคาเท่ากันหมด
  //   เลิกแยก "ใบ 1 / ใบ 2" (JR00304/JR00305) แล้ว — นับ 1 ชุดต่อบาน รหัสจริงเลือกที่ใบตัด (สี × ด้าน)
  ok('มือจับหน้าต่าง = 1 ชุด/บาน (บานเดี่ยว)', hw(w1, 'JR00318') === 1, String(hw(w1, 'JR00318')));
