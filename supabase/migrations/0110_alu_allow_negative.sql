-- 0110_alu_allow_negative — อลูตัดได้เสมอแม้ยอดไม่พอ (ติดลบได้) · เจ้าของเคาะ 24 ก.ค.2569
--   เหตุ: ร้านไม่ได้นับอลูเป็นเส้นเข้าสต็อก (88-94% ยอด=0) → ตัดใบตัดที่มีอลูแล้วหักไม่ลง (ชนกฎ qty>=0)
--         → ไม่มีรายการเบิกอลูในสมุดสโตร์ · ต้องการให้บันทึกการใช้อลูเต็มเสมอ (โชว์ว่าใช้อลูอะไรไปงานไหน)
--   วิธี: ปลดกฎห้ามติดลบ "เฉพาะหมวดอลูมิเนียม" · ของอื่น (อุปกรณ์/กระจก/เครื่องมือ) ยังกันติดลบไว้จับ error
--   อลูติดลบ = "ใช้เกินที่ระบบนับไว้" (สัญญาณ) → สโตร์นับ + กด "ปรับให้ตรง" ในสมุดสโตร์ทีหลังได้
--   ⚠ money-sensitive: เดิม accountant กันติดลบ · เจ้าของ override เฉพาะอลู (ควรแจ้งผู้สอบบัญชีทราบ)
alter table public.stock_items drop constraint if exists stock_items_qty_nonneg;
alter table public.stock_items add constraint stock_items_qty_nonneg
  check (qty_on_hand >= 0 or category = 'อลูมิเนียม');
