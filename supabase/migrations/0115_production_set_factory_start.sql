-- 0115 · เริ่มผลิตแยกโรง (per-factory start date) ต่อชุดงาน
-- ปัญหา: ฟีเจอร์แยกโรง (0114 factories text[]) เลือกได้ว่าชุดนี้ทำโรงไหน แต่ตั้ง "วันเริ่มผลิต" แยกโรงไม่ได้
--   เคสจริง: งานคุณเอ โรง3 เริ่ม 12, โรง1 เริ่ม 18 — ต้องตั้งคนละวันในหน้าผลิต
-- วิธี: เก็บ jsonb map ชื่อโรง → วันเริ่มผลิต (ISO date) เช่น {"โรงงาน 1":"2026-08-18","โรงงาน 3":"2026-08-12"}
--   ไม่แตะ factories (คงเป็นตัวเลือกว่าชุดนี้อยู่โรงไหน) · start เก็บแยกเพื่อไม่พังโครงเดิม/parity ลิงก์ช่าง
-- idempotent · เจ้าของรัน · ไม่กระทบข้อมูลเดิม
-- ============================================================

alter table public.production_sets
  add column if not exists factory_start jsonb not null default '{}'::jsonb;

comment on column public.production_sets.factory_start is
  'วันเริ่มผลิตแยกโรง — map ชื่อโรง→ISO date (0115) เช่น {"โรงงาน 1":"2026-08-18"}';
