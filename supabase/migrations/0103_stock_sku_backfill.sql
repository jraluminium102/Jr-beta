-- 0103 · เติมรหัส (sku) ให้วัสดุที่ยังไม่มีรหัส = 'JR' + id (5 หลัก)
--   จุดประสงค์: ให้ทุกวัสดุมี "รหัสสั้นภาษาอังกฤษ" ไว้อ้างอิงข้ามระบบ/คุยกับ AI อื่น
--   • ผูกกับ id (PK) → ไม่มีทางซ้ำ · รันซ้ำได้ผลเดิม (idempotent)
--   • ไม่แตะรหัสอลูเดิม B####/F####/E-##/WM-K## และ STEEL box1/plate (where กันไว้แล้ว)
--   • ไม่ชน calcLink: 'JR#####' ไม่ตรง aluCodes/steelKeys → ไม่ทำให้ลิงก์คิดราคา 4.0 เพี้ยน
-- idempotent · เจ้าของรัน · ไม่แตะข้อมูลราคา/ยอด
-- หมายเหตุ: รอบ go-live นี้ backfill ถูกยิงผ่าน API แอปไปแล้ว — migration นี้เก็บไว้เป็นหลักฐาน
--           และกันกรณี rebuild DB (ถ้ามีแถวรหัสว่างจะเติมให้เหมือนกัน)
-- ============================================================

update public.stock_items
set sku = 'JR' || lpad(id::text, 5, '0')
where sku is null or btrim(sku) = '';
