/** ตัวเลือก "แทนกระจก" (ไม่อยู่ในตารางราคากระจก — engine คิดเป็นแผ่น/เกล็ด ดู isPanelGlass) */
export const GLASS_EXTRA = ['แผ่นคอมโพสิต', 'แผ่นลูกฟูก', 'เกล็ด Z 1"', 'เกล็ด Z 1.6"'];

const NAME_TO_KEY = new Map(GLASS_NAMED);
const KEY_TO_NAME = new Map();   // คีย์ราคา → ชื่อโชว์ตัวแรกที่ชี้มา (ใบเก่า)
for (const [name, key] of GLASS_NAMED) if (!KEY_TO_NAME.has(key)) KEY_TO_NAME.set(key, name);

/** คีย์ราคาใน PB.GLASS จากค่าที่เก็บ (ชื่อโชว์ หรือคีย์ราคาเดิม) */
export function glassPriceKey(v) {
  const s = String(v ?? '');
  return NAME_TO_KEY.get(s) || s;
}

/** ชื่อโชว์แบบแปลงอัตโนมัติ สำหรับคีย์ที่เจ้าของไม่ได้ตั้งชื่อ: "เขียว 6มม." → "เขียว หนา 6 มม." · ตัดคำ "กระจก" นำหน้า */
function autoName(key) {
  let s = String(key ?? '').replace(/^กระจก\s*/, '');
  s = s.replace(/\s*(\d+(?:\.\d+)?)\s*มม\.?/, ' หนา $1 มม.');
  return s.replace(/\s{2,}/g, ' ').trim();
}

/** ชื่อโชว์ (ใบเสนอ/ดรอปดาวน์) จากค่าที่เก็บ */
export function glassDisplayName(v) {
  const s = String(v ?? '');
  if (!s) return '';
  if (NAME_TO_KEY.has(s)) return s;            // เป็นชื่อโชว์อยู่แล้ว
  if (KEY_TO_NAME.has(s)) return KEY_TO_NAME.get(s);   // ใบเก่าเก็บคีย์ราคา
  if (GLASS_EXTRA.includes(s)) return s;
  return autoName(s);
}

/** ค่าที่ควรเก็บ/เลือกในดรอปดาวน์ จากค่าที่มีอยู่ (คีย์ราคาเดิมของตัวที่มีชื่อโชว์ → ชื่อโชว์) */
export function glassCanonical(v) {
  const s = String(v ?? '');
  return KEY_TO_NAME.get(s) || s;
}

/**
 * รายการตัวเลือกในดรอปดาวน์ — 3 กลุ่มตามลำดับ:
 *   ① ตามลิสต์เจ้าของ (เฉพาะที่มีราคาใน PB) · ② ที่เหลือใน PB (ชื่อแปลงอัตโนมัติ · ค่าเก็บ = คีย์ราคา) · ③ แทนกระจก
 */
export function glassOptionGroups(PB) {
  const G = (PB && PB.GLASS) || {};
  const used = new Set();
  const named = [];
  for (const [name, key] of GLASS_NAMED) {
    if (!(G[key] > 0)) continue;
    named.push({ value: name, label: name });
    used.add(key);
  }
  const rest = Object.keys(G).filter((k) => !used.has(k)).map((k) => ({ value: k, label: autoName(k) }));
  const extra = GLASS_EXTRA.map((k) => ({ value: k, label: k }));
  return [
    { cat: 'รายการหลัก', items: named },
    ...(rest.length ? [{ cat: 'อื่น ๆ (ยังไม่จัดชื่อ)', items: rest }] : []),
    { cat: 'แทนกระจก', items: extra },
  ];
}

/** รายการค่าทั้งหมดแบบแบน (value) — ใช้แทน allGlassKeys เดิม */
export function glassOptionValues(PB) {
  return glassOptionGroups(PB).flatMap((g) => g.items.map((i) => i.value));
}
